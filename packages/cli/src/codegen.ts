import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, sep } from "node:path";
import { compileRoutes, RouteDefinitionError } from "@sabit/router";
import { scanRoutes } from "@sabit/router/fs";
import type { Output } from "./command.ts";
import { detectImportExtension } from "./scaffold.ts";

/** File name of the generated route tree, next to the routes directory. */
export const ROUTE_TREE_FILE = "sabit.route.ts";

/** Where the route tree for a routes directory lives: `src/routes` → `src/sabit.route.ts`. */
export function routeTreePath(routesDir: string): string {
  return join(dirname(routesDir), ROUTE_TREE_FILE);
}

export interface RouteTreeOptions {
  readonly routesDir: string;
  /** Output file. Defaults to {@link routeTreePath}. */
  readonly outFile?: string;
  /** Extension for import specifiers: `.ts` to run TypeScript directly, `.js` for tsc-compiled projects. */
  readonly importExtension?: ".ts" | ".js";
}

/**
 * Builds the source of the route tree: a module that statically imports every
 * route and middleware file, so the server doesn't scan the filesystem at
 * startup and bundlers can see every route. Throws a `RouteDefinitionError`
 * when the routes directory has conflicts or invalid file names.
 */
export async function generateRouteTree(options: RouteTreeOptions): Promise<string> {
  const { routesDir } = options;
  const outFile = options.outFile ?? routeTreePath(routesDir);
  const ext = options.importExtension ?? ".ts";
  const { routes, middleware, schemas } = await scanRoutes(routesDir);
  const compiled = compileRoutes({ routes, middleware, schemas });
  const appMiddlewareFile = join(dirname(routesDir), "middleware.ts");
  const hasAppMiddleware = existsSync(appMiddlewareFile);

  const specifier = (file: string) => {
    let path = relative(dirname(outFile), join(routesDir, file)).split(sep).join("/");
    if (!path.startsWith(".")) path = `./${path}`;
    return ext === ".js" ? path.replace(/\.ts$/, ".js").replace(/\.mts$/, ".mjs") : path;
  };

  const routeIds = new Map(compiled.map((route, i) => [route.file, `route${i}`]));
  const middlewareIds = new Map(middleware.map((file, i) => [file, `middleware${i}`]));
  const schemaIds = new Map(schemas.map((file, i) => [file, `schema${i}`]));
  const appPath = relative(dirname(outFile), appMiddlewareFile).split(sep).join("/");
  const appSpecifier = (appPath.startsWith(".") ? appPath : `./${appPath}`).replace(/\.ts$/, ext);
  const label = relative(dirname(outFile), routesDir).split(sep).join("/") || ".";

  const lines: string[] = [
    "/* eslint-disable */",
    `// Generated by sabit from ${label}/. Don't edit this file:`,
    "// `sabit dev`, `sabit add` and `sabit generate` keep it up to date.",
    "",
    'import type { RouteSources } from "@sabit/router";',
    ...(hasAppMiddleware ? [`import * as appMiddleware from "${appSpecifier}";`] : []),
    ...schemas.map((file) => `import * as ${schemaIds.get(file)} from "${specifier(file)}";`),
    ...middleware.map(
      (file) => `import * as ${middlewareIds.get(file)} from "${specifier(file)}";`,
    ),
    ...compiled.map(
      (route) => `import * as ${routeIds.get(route.file)} from "${specifier(route.file)}";`,
    ),
    "",
    "/** Every route and middleware file. Pass it to `resolveRoutes()` from @sabit/router. */",
    "export const routeTree = {",
    "  routes: [",
    ...compiled.map(
      (route) =>
        `    { file: ${JSON.stringify(route.file)}, load: () => ${routeIds.get(route.file)} }, // ${route.pattern}`,
    ),
    "  ],",
    "  middleware: [",
    ...middleware.map(
      (file) => `    { file: ${JSON.stringify(file)}, load: () => ${middlewareIds.get(file)} },`,
    ),
    "  ],",
    "  schemas: [",
    ...schemas.map(
      (file) => `    { file: ${JSON.stringify(file)}, load: () => ${schemaIds.get(file)} },`,
    ),
    "  ],",
    ...(hasAppMiddleware
      ? ['  appMiddleware: { file: "../middleware.ts", load: () => appMiddleware },']
      : []),
    "} satisfies RouteSources;",
    "",
    "/** Every URL pattern in the app. */",
    compiled.length === 0
      ? "export type RoutePattern = never;"
      : `export type RoutePattern =\n${compiled.map((r) => `  | ${JSON.stringify(r.pattern)}`).join("\n")};`,
    "",
    "/** Route modules by URL pattern, for typed tooling. */",
    "export interface RouteModules {",
    ...compiled.map(
      (route) => `  ${JSON.stringify(route.pattern)}: typeof ${routeIds.get(route.file)};`,
    ),
    "}",
    "",
  ];
  return lines.join("\n");
}

/** Writes the route tree if its content changed. Returns whether it wrote. */
export async function writeRouteTree(options: RouteTreeOptions): Promise<boolean> {
  const outFile = options.outFile ?? routeTreePath(options.routesDir);
  const content = await generateRouteTree(options);
  const current = existsSync(outFile) ? await readFile(outFile, "utf8") : undefined;
  if (current === content) return false;
  await writeFile(outFile, content);
  return true;
}

/**
 * Regenerates the route tree. Unless `create` is set, only does so when the
 * file already exists (projects opt in by having it). Reports errors instead
 * of throwing, so watchers keep running. Returns false on errors.
 */
export async function refreshRouteTree(
  cwd: string,
  routesDir: string,
  out: Output,
  options: { create?: boolean; quiet?: boolean } = {},
): Promise<boolean> {
  const outFile = routeTreePath(routesDir);
  if (!options.create && !existsSync(outFile)) return true;
  const label = relative(cwd, outFile) || outFile;
  try {
    const wrote = await writeRouteTree({
      routesDir,
      outFile,
      importExtension: detectImportExtension(cwd),
    });
    if (wrote) out.log(`  updated  ${label}`);
    else if (!options.quiet) out.log(`  current  ${label}`);
    return true;
  } catch (error) {
    if (!(error instanceof RouteDefinitionError)) throw error;
    out.error(`Couldn't update ${label}:\n${error.message}`);
    return false;
  }
}
